bool f[R+5][C+5];
char dir[R+5][C+5], c[4]={'V', '^', '<', '>'};
deque<pair<int,int>> dq;

void dfs (int nr, int nc, int tr, int tc, int vis){
    mx=max(mx,vis);
    if (vis>=R*C){
        if (nr==1 && nc>=9){
            for (int i=R;i>0;i--){
                for (int j=1;j<=C;j++){
                    cout << dir[i][j];
                }
                cout << '\n';
            }
            cout << '\n';
            for (auto [f,s]:dq) cout << f << ' ' << s << '\n';
            exit(0);
        }
        return;
    }
    for (int i=0;i<4;i++){
        int xr=nr+d[i][0], xc=nc+d[i][1];
        if (xr<1 || xc<1 || xr>R || xc>C || f[xr][xc] || cell[xr][xc]) continue;
        f[xr][xc]=1;
        dir[nr][nc]=c[i];
        dq.emplace_back(xr,xc);
        dfs(xr,xc,tr,tc,vis+1);
        dq.pop_back();
        dir[nr][nc]='.';
        f[xr][xc]=0;
    }
}

